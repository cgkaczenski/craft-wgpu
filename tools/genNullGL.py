#!/usr/bin/env python3
"""Generates src/platform/nullGLStubs.inl from the vendored glad header.

The WebGPU path has no OpenGL context, so glad's function pointers would be
null and the first GL call would crash. nullGL.cpp fills every pointer with a
stub from this file instead (docs/roadmap.md, milestone 2).

Each stub has the exact signature of its glad typedef, does nothing and
returns a zero value. Functions shaped like glGen*/glCreate*(..., GLsizei n,
GLuint *ids) hand out fresh nonzero names, because code treats a 0 name as a
failed load. nullGL.cpp overrides the few functions whose answers the game
acts on.

Run from the repository root after changing glad:
    python3 tools/genNullGL.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GLAD_HEADER = ROOT / "thirdparty/glad/include/glad/glad.h"
OUTPUT = ROOT / "src/platform/nullGLStubs.inl"

TYPEDEF = re.compile(r"^typedef (.+?) \(APIENTRYP (PFNGL\w+PROC)\)\((.*)\);$")
POINTER = re.compile(r"^GLAPI (PFNGL\w+PROC) glad_(gl\w+);$")
# The last two parameters of glGen*/glCreate* style functions.
NAMES_OUT = re.compile(r"(?:^|, )GLsizei n, GLuint \*(\w+)$")


def main():
	typedefs = {}
	functions = []

	for line in GLAD_HEADER.read_text().splitlines():
		m = TYPEDEF.match(line)
		if m:
			returnType, typedefName, params = m.groups()
			typedefs[typedefName] = (returnType, params)
			continue

		m = POINTER.match(line)
		if m:
			typedefName, functionName = m.groups()
			functions.append((functionName, typedefName))

	if not functions:
		sys.exit(f"No GL functions found in {GLAD_HEADER}; did glad's format change?")

	out = [
		"// Generated by tools/genNullGL.py from thirdparty/glad/include/glad/glad.h.",
		"// Do not edit; rerun the script instead. Included only by nullGL.cpp.",
		"",
	]

	for functionName, typedefName in functions:
		returnType, params = typedefs[typedefName]
		if params == "void":
			params = ""

		names = NAMES_OUT.search(params) if functionName.startswith(("glGen", "glCreate")) else None
		if names:
			body = f" nullGLNewNames(n, {names.group(1)}); "
		elif returnType == "void":
			body = ""
		else:
			body = " return {}; "

		out.append(f"static {returnType} APIENTRY null_{functionName}({params}) {{{body}}}")

	out += ["", "static void installGeneratedStubs()", "{"]
	out += [f"\tglad_{name} = null_{name};" for name, _ in functions]
	out += ["}", ""]

	OUTPUT.write_text("\n".join(out))
	print(f"Wrote {len(functions)} stubs to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
